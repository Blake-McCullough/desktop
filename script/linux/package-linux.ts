import * as cp from 'child_process'
import * as crypto from 'crypto'
import * as Path from 'path'
import {
  chmodSync,
  copyFileSync,
  cpSync,
  existsSync,
  linkSync,
  lstatSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  unlinkSync,
  writeFileSync,
} from 'fs'

/** The command, folder, icon and desktop-entry name on Linux. */
export const LinuxAppId = 'github-desktop-custom'

/**
 * The URL schemes the app handles (see `protocols` in build.ts). GitHub
 * sign-in comes back through `x-github-desktop-auth`, so the desktop entry
 * has to claim it for signing in to work.
 */
const Schemes = ['x-github-desktop-auth', 'x-github-client', 'github-mac']

export interface ILinuxPackageOptions {
  /** The packaged app folder (contains the executable). */
  readonly appDir: string
  /** Where to write the packages. */
  readonly outputDir: string
  readonly productName: string
  readonly version: string
  /** `x64` or `arm64`. */
  readonly arch: string
  /** 512×512 PNG icon. */
  readonly iconPath: string
  readonly homepage: string
}

function desktopEntry(productName: string, exec: string) {
  return [
    '[Desktop Entry]',
    `Name=${productName}`,
    'Comment=GitHub Desktop with repository groups, GitLab CI/CD pipelines and a history graph',
    `Exec=${exec} %U`,
    `Icon=${LinuxAppId}`,
    'Type=Application',
    'Terminal=false',
    'Categories=Development;RevisionControl;',
    `StartupWMClass=${productName}`,
    `MimeType=${Schemes.map(s => `x-scheme-handler/${s};`).join('')}`,
    '',
  ].join('\n')
}

/** pacman versions can't contain '-'; 3.6.11-custom1-b00004 → 3.6.11.custom1.b00004 */
export function toPacmanVersion(version: string) {
  return version.replace(/-/g, '.')
}

function pkgbuild(
  options: ILinuxPackageOptions,
  tarballName: string,
  sha256: string
) {
  return `# Maintainer: Blake McCullough
# Generated by script/linux/package-linux.ts for ${options.version}.
# Build and install with: makepkg -si

pkgname=${LinuxAppId}-bin
pkgver=${toPacmanVersion(options.version)}
pkgrel=1
pkgdesc="GitHub Desktop with repository groups, GitLab CI/CD pipelines and a history graph"
arch=('x86_64')
url="${options.homepage}"
license=('MIT')
depends=('gtk3' 'nss' 'alsa-lib' 'libsecret' 'xdg-utils')
optdepends=('git: a system git (the app bundles its own)')
provides=('${LinuxAppId}')
conflicts=('${LinuxAppId}')
options=('!strip' '!debug')
install=${LinuxAppId}.install
source=("${tarballName}")
sha256sums=('${sha256}')

package() {
  install -d "$pkgdir/opt/${LinuxAppId}"
  cp -a "$srcdir/${LinuxAppId}/." "$pkgdir/opt/${LinuxAppId}/"
  # Must be enterable by every user, not just root.
  chmod 755 "$pkgdir/opt/${LinuxAppId}"

  # Installed as root by pacman, so Chromium's setuid sandbox helper can be
  # set up properly (an AppImage or tarball can't do this).
  chmod 4755 "$pkgdir/opt/${LinuxAppId}/chrome-sandbox"

  install -d "$pkgdir/usr/bin"
  ln -s "/opt/${LinuxAppId}/${LinuxAppId}" "$pkgdir/usr/bin/${LinuxAppId}"

  install -Dm644 "$srcdir/${LinuxAppId}/${LinuxAppId}.desktop" \\
    "$pkgdir/usr/share/applications/${LinuxAppId}.desktop"
  install -Dm644 "$srcdir/${LinuxAppId}/${LinuxAppId}.png" \\
    "$pkgdir/usr/share/icons/hicolor/512x512/apps/${LinuxAppId}.png"
  install -Dm644 "$srcdir/${LinuxAppId}/LICENSE" \\
    "$pkgdir/usr/share/licenses/$pkgname/LICENSE"
}
`
}

/**
 * pacman install hooks. pacman doesn't change the permissions of a folder
 * that already exists when upgrading, so upgrades from builds where
 * /opt/github-desktop-custom was 700 (root-only) would stay broken
 * without this.
 */
const PacmanInstallScript = `post_install() {
  chmod 755 /opt/${LinuxAppId}
}

post_upgrade() {
  post_install
}
`

/** AppImage entry point: picks the sandbox mode the system supports. */
const AppRun = `#!/bin/sh
HERE="$(dirname "$(readlink -f "$0")")"
EXTRA=""
# Chromium's sandbox needs unprivileged user namespaces when its setuid
# helper isn't available (it can't be inside an AppImage). Some systems
# restrict those (e.g. Ubuntu 24.04+ via AppArmor); fall back there.
if [ "$(cat /proc/sys/kernel/unprivileged_userns_clone 2>/dev/null)" = "0" ] ||
   [ "$(cat /proc/sys/kernel/apparmor_restrict_unprivileged_userns 2>/dev/null)" = "1" ]; then
  EXTRA="--no-sandbox"
fi
exec "$HERE/usr/lib/${LinuxAppId}/${LinuxAppId}" $EXTRA "$@"
`

/**
 * Replace identical files with hard links. The bundled git ships ~170
 * commands that are byte-for-byte copies of one 4 MB binary (hard links in
 * the original); copying the app turns them into separate files and adds
 * ~700 MB. tar and pacman both preserve hard links.
 */
function hardLinkDuplicates(dir: string) {
  const bySize = new Map<number, Array<string>>()
  const walk = (current: string) => {
    for (const entry of readdirSync(current, { withFileTypes: true })) {
      const full = Path.join(current, entry.name)
      if (entry.isDirectory()) {
        walk(full)
      } else if (entry.isFile()) {
        const size = lstatSync(full).size
        if (size >= 64 * 1024) {
          const list = bySize.get(size) ?? []
          list.push(full)
          bySize.set(size, list)
        }
      }
    }
  }
  walk(dir)

  let saved = 0
  for (const [size, files] of bySize) {
    if (files.length < 2) {
      continue
    }
    const firstByHash = new Map<string, string>()
    for (const file of files) {
      const hash = crypto
        .createHash('sha256')
        .update(readFileSync(file))
        .digest('hex')
      const original = firstByHash.get(hash)
      if (original === undefined) {
        firstByHash.set(hash, file)
        continue
      }
      // Keep the original's permissions (e.g. executable bits).
      const mode = lstatSync(file).mode
      if (lstatSync(original).mode !== mode) {
        continue
      }
      unlinkSync(file)
      linkSync(original, file)
      saved += size
    }
  }

  console.log(
    `Hard-linked duplicate files, saving ${Math.round(saved / 1024 / 1024)} MB`
  )
}

/**
 * Make everything readable (and folders enterable) by all users. Electron
 * Packager creates the app folder with mode 700; copied as-is, that made
 * /opt/github-desktop-custom root-only, so launching it as a normal user
 * failed with "could not find the program".
 */
function makeWorldReadable(dir: string) {
  const fix = (path: string) => {
    const stat = lstatSync(path)
    if (stat.isSymbolicLink()) {
      return
    }
    if (stat.isDirectory()) {
      chmodSync(path, (stat.mode & 0o7777) | 0o755)
      for (const entry of readdirSync(path)) {
        fix(Path.join(path, entry))
      }
    } else if (stat.isFile()) {
      // Readable by everyone; executable by everyone if the owner can run it.
      const exec = stat.mode & 0o100 ? 0o055 : 0
      chmodSync(path, (stat.mode & 0o7777) | 0o044 | exec)
    }
  }
  fix(dir)
}

function run(command: string, args: ReadonlyArray<string>, env = {}) {
  // eslint-disable-next-line no-sync
  const result = cp.spawnSync(command, args, {
    stdio: 'inherit',
    env: { ...process.env, ...env },
  })
  if (result.status !== 0) {
    throw new Error(`${command} ${args.join(' ')} failed (${result.status})`)
  }
}

/**
 * Produce the Linux packages:
 *
 * - `<Product>-<version>-linux-<arch>.tar.gz`: the app plus its desktop
 *   entry and icon, in a `github-desktop-custom/` folder.
 * - `PKGBUILD`: an Arch Linux (CachyOS, Manjaro, …) package recipe for that
 *   tarball; `makepkg -si` next to the tarball installs it.
 * - `<Product>-<version>-<arch>.AppImage`, when `APPIMAGETOOL` points at
 *   appimagetool (the release workflow provides it).
 */
export function packageLinux(options: ILinuxPackageOptions) {
  const { appDir, outputDir, productName, version, arch } = options
  const fileBase = productName.replace(/\s+/g, '')
  const staging = Path.join(outputDir, 'linux-staging')
  rmSync(staging, { recursive: true, force: true })

  // 1. tar.gz
  const tarRoot = Path.join(staging, LinuxAppId)
  cpSync(appDir, tarRoot, { recursive: true, verbatimSymlinks: true })
  writeFileSync(
    Path.join(tarRoot, `${LinuxAppId}.desktop`),
    desktopEntry(productName, LinuxAppId)
  )
  copyFileSync(options.iconPath, Path.join(tarRoot, `${LinuxAppId}.png`))
  makeWorldReadable(tarRoot)
  hardLinkDuplicates(tarRoot)

  const tarballName = `${fileBase}-${version}-linux-${arch}.tar.gz`
  const tarball = Path.join(outputDir, tarballName)
  console.log(`Creating ${tarball}…`)
  run('tar', ['-czf', tarball, '-C', staging, LinuxAppId])

  // 2. PKGBUILD (x64 only — Arch's main repos are x86_64)
  if (arch === 'x64') {
    const sha256 = crypto
      .createHash('sha256')
      .update(readFileSync(tarball))
      .digest('hex')
    writeFileSync(
      Path.join(outputDir, 'PKGBUILD'),
      pkgbuild(options, tarballName, sha256)
    )
    writeFileSync(
      Path.join(outputDir, `${LinuxAppId}.install`),
      PacmanInstallScript
    )
    console.log('Wrote PKGBUILD')
  }

  // 3. AppImage
  const appImageTool = process.env.APPIMAGETOOL
  if (appImageTool === undefined || !existsSync(appImageTool)) {
    console.log('APPIMAGETOOL not set; skipping AppImage')
  } else {
    const appDirPath = Path.join(staging, 'AppDir')
    const libDir = Path.join(appDirPath, 'usr', 'lib', LinuxAppId)
    mkdirSync(Path.dirname(libDir), { recursive: true })
    cpSync(appDir, libDir, { recursive: true, verbatimSymlinks: true })

    writeFileSync(Path.join(appDirPath, 'AppRun'), AppRun)
    chmodSync(Path.join(appDirPath, 'AppRun'), 0o755)
    writeFileSync(
      Path.join(appDirPath, `${LinuxAppId}.desktop`),
      desktopEntry(productName, LinuxAppId)
    )
    copyFileSync(options.iconPath, Path.join(appDirPath, `${LinuxAppId}.png`))
    copyFileSync(options.iconPath, Path.join(appDirPath, '.DirIcon'))
    makeWorldReadable(appDirPath)

    const appImage = Path.join(
      outputDir,
      `${fileBase}-${version}-${arch}.AppImage`
    )
    console.log(`Creating ${appImage}…`)
    run(appImageTool, [appDirPath, appImage], {
      ARCH: arch === 'arm64' ? 'aarch64' : 'x86_64',
      // CI runners don't have FUSE to mount appimagetool itself.
      APPIMAGE_EXTRACT_AND_RUN: '1',
    })
  }

  rmSync(staging, { recursive: true, force: true })
}
